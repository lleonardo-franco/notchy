import AppKit
import Observation

struct ClipItem: Identifiable, Equatable {
    enum Kind {
        case text(String)
        case image(NSImage)
        case file(URL)
    }

    let id = UUID()
    let kind: Kind
    var date: Date

    static func == (lhs: ClipItem, rhs: ClipItem) -> Bool {
        lhs.id == rhs.id && lhs.date == rhs.date
    }

    var text: String? {
        if case .text(let value) = kind { return value }
        return nil
    }

    var fileURL: URL? {
        if case .file(let url) = kind { return url }
        return nil
    }

    var preview: String {
        switch kind {
        case .text(let value):
            return String(value.prefix(400)).split(whereSeparator: \.isWhitespace).joined(separator: " ")
        case .image(let image):
            return String(localized: "Imagem \(Int(image.size.width))×\(Int(image.size.height))")
        case .file(let url):
            return url.lastPathComponent
        }
    }
}

@MainActor
@Observable
final class ClipboardService {
    static let limit = 30
    static let imageLimit = 8

    private static let ignored: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]

    private(set) var items: [ClipItem] = []

    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                guard !SystemActivity.shared.paused else { return }
                self?.poll()
            }
        }
    }

    func copy(_ item: ClipItem) {
        let board = NSPasteboard.general
        board.clearContents()
        switch item.kind {
        case .text(let value):
            board.setString(value, forType: .string)
        case .image(let image):
            board.writeObjects([image])
        case .file(let url):
            board.writeObjects([url as NSURL])
        }
        changeCount = board.changeCount
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: index)
        moved.date = Date()
        items.insert(moved, at: 0)
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
    }

    func clear() {
        items.removeAll()
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount

        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignored) else { return }

        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let url = urls.first {
            insert(.file(url))
        } else if let text = board.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(.text(text))
        } else if let image = NSImage(pasteboard: board) {
            insert(.image(image))
        }
    }

    private func insert(_ kind: ClipItem.Kind) {
        switch kind {
        case .text(let value):
            items.removeAll { $0.text == value }
        case .file(let url):
            items.removeAll { $0.fileURL == url }
        case .image:
            break
        }
        items.insert(ClipItem(kind: kind, date: Date()), at: 0)

        var images = 0
        items = items.filter { item in
            guard case .image = item.kind else { return true }
            images += 1
            return images <= Self.imageLimit
        }
        if items.count > Self.limit {
            items.removeLast(items.count - Self.limit)
        }
    }
}
